/**
 * システムプロンプトを構築する (現在日付を付与)。
 * @param {string} mode 'lite' (既定・省トークン) | 'full' (リッチ)
 * @returns {string}
 */
function buildSystemPrompt(mode) {
  /* 時刻は入れず「日付のみ」にする: システムプロンプトの前置きが1日単位で完全一致し、
     Groq のプロンプトキャッシュに乗りやすくなる (キャッシュ済みトークンはレート制限に不算入) */
  const now = new Date();
  const dateStr = now.getFullYear() + '年' + (now.getMonth() + 1) + '月' + now.getDate() + '日';
  const persona = (mode === 'full') ? LAIN_PERSONA : LAIN_PERSONA_LITE;
  return persona + '\n\n# 現在の日付\n今日は ' + dateStr + ' です。「最新」「今日」「最近」などの時間表現を解釈するときの基準にしてください。';
}

